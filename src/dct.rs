fn identity_scale(size: usize) -> i64 {
    match size {
        4 => 128,
        8 => 181,
        16 => 256,
        32 => 362,
        _ => 128,
    }
}

fn kernel_value(tx_1d: TxType1D, size: usize, freq: usize, spatial: usize) -> i64 {
    match tx_1d {
        TxType1D::DCT2 => match size {
            4 => FWD_DCT2_4[freq][spatial] as i64,
            8 => FWD_DCT2_8[freq][spatial] as i64,
            16 => FWD_DCT2_16[freq][spatial] as i64,
            32 => FWD_DCT2_32[freq][spatial] as i64,
            _ => unreachable!(),
        },
        TxType1D::DST7 => match size {
            4 => INV_ADST_4[freq][spatial] as i64,
            8 => INV_ADST_8[freq][spatial] as i64,
            16 => INV_ADST_16[freq][spatial] as i64,
            _ => unreachable!(),
        },
        TxType1D::DCT8 => match size {
            4 => INV_FLIPADST_4[freq][spatial] as i64,
            8 => INV_FLIPADST_8[freq][spatial] as i64,
            16 => INV_FLIPADST_16[freq][spatial] as i64,
            _ => unreachable!(),
        },
        TxType1D::IDT => {
            if freq == spatial {
                identity_scale(size)
            } else {
                0
            }
        }
    }
}

fn round_shift(value: i64, shift: u32) -> i32 {
    ((value + (1i64 << (shift - 1))) >> shift) as i32
}

pub fn forward_dct2_64x64(residual: &[i32; 4096]) -> [i32; 1024] {
    let mut temp = [[0i32; 64]; 64];

    for col in 0..64 {
        for freq_row in 0..64 {
            let mut sum = 0i64;
            for spatial_row in 0..64 {
                sum += FWD_DCT2_64[freq_row][spatial_row] as i64
                    * residual[spatial_row * 64 + col] as i64;
            }
            temp[freq_row][col] = round_shift(sum, 3);
        }
    }

    let mut output = [0i32; 1024];
    for freq_row in 0..32 {
        for freq_col in 0..32 {
            let mut sum = 0i64;
            for spatial_col in 0..64 {
                sum +=
                    FWD_DCT2_64[freq_col][spatial_col] as i64 * temp[freq_row][spatial_col] as i64;
            }
            output[freq_row * 32 + freq_col] = round_shift(sum, 14);
        }
    }

    output
}

