const NEW_INV_SQRT2: i64 = 2896;
const NEW_SQRT2_BITS: u32 = 12;

fn kernel_row(size: usize, freq: usize, spatial: usize) -> i64 {
    match size {
        4 => FWD_DCT2_4[freq][spatial] as i64,
        8 => FWD_DCT2_8[freq][spatial] as i64,
        16 => FWD_DCT2_16[freq][spatial] as i64,
        32 => FWD_DCT2_32[freq][spatial] as i64,
        _ => unreachable!(),
    }
}

pub fn inverse_dct2_rect(
    coeffs: &[i32],
    out_w: usize,
    out_h: usize,
    coded_w: usize,
    coded_h: usize,
    shift1: u32,
    shift2: u32,
    sqrt2: bool,
) -> Vec<i32> {
    let mut input = vec![0i32; coded_w * coded_h];
    let n = coeffs.len().min(coded_w * coded_h);
    input[..n].copy_from_slice(&coeffs[..n]);

    if sqrt2 {
        for v in &mut input {
            *v = round_shift(*v as i64 * NEW_INV_SQRT2, NEW_SQRT2_BITS);
        }
    }

    let mut temp = vec![0i32; coded_h * coded_w];
    for row in 0..coded_h {
        for spatial_col in 0..coded_w {
            let mut sum = 0i64;
            for freq_col in 0..coded_w {
                sum += kernel_row(coded_w, freq_col, spatial_col)
                    * input[row * coded_w + freq_col] as i64;
            }
            temp[row * coded_w + spatial_col] = round_shift(sum, shift1);
        }
    }

    let mut intermediate = vec![0i32; coded_h * coded_w];
    for col in 0..coded_w {
        for spatial_row in 0..coded_h {
            let mut sum = 0i64;
            for freq_row in 0..coded_h {
                sum += kernel_row(coded_h, freq_row, spatial_row)
                    * temp[freq_row * coded_w + col] as i64;
            }
            intermediate[spatial_row * coded_w + col] = round_shift(sum, shift2);
        }
    }

    let expand_w = out_w > coded_w;
    let expand_h = out_h > coded_h;

    if !expand_w && !expand_h {
        return intermediate;
    }

    let mut output = vec![0i32; out_w * out_h];
    for row in 0..coded_h {
        for col in 0..coded_w {
            let val = intermediate[row * coded_w + col];
            if expand_w && expand_h {
                output[(2 * row) * out_w + 2 * col] = val;
                output[(2 * row) * out_w + 2 * col + 1] = val;
                output[(2 * row + 1) * out_w + 2 * col] = val;
                output[(2 * row + 1) * out_w + 2 * col + 1] = val;
            } else if expand_w {
                output[row * out_w + 2 * col] = val;
                output[row * out_w + 2 * col + 1] = val;
            } else {
                output[(2 * row) * out_w + col] = val;
                output[(2 * row + 1) * out_w + col] = val;
            }
        }
    }

    output
}

pub fn inverse_transform_2d_rect(
    coeffs: &[i32],
    out_w: usize,
    out_h: usize,
    coded_w: usize,
    coded_h: usize,
    tx_type: usize,
    shift1: u32,
    shift2: u32,
    sqrt2: bool,
) -> Vec<i32> {
    let hor_type = get_hor_tx_type_1d(tx_type);
    let ver_type = get_ver_tx_type_1d(tx_type);

    let mut input = vec![0i32; coded_w * coded_h];
    let n = coeffs.len().min(coded_w * coded_h);
    input[..n].copy_from_slice(&coeffs[..n]);

    if sqrt2 {
        for v in &mut input {
            *v = round_shift(*v as i64 * NEW_INV_SQRT2, NEW_SQRT2_BITS);
        }
    }

    let mut temp = vec![0i32; coded_h * coded_w];
    if hor_type == TxType1D::IDT {
        let scale = identity_scale(coded_w);
        for row in 0..coded_h {
            for col in 0..coded_w {
                temp[row * coded_w + col] =
                    round_shift(input[row * coded_w + col] as i64 * scale, shift1);
            }
        }
    } else {
        for row in 0..coded_h {
            for spatial_col in 0..coded_w {
                let mut sum = 0i64;
                for freq_col in 0..coded_w {
                    sum += kernel_value(hor_type, coded_w, freq_col, spatial_col)
                        * input[row * coded_w + freq_col] as i64;
                }
                temp[row * coded_w + spatial_col] = round_shift(sum, shift1);
            }
        }
    }

    let mut intermediate = vec![0i32; coded_h * coded_w];
    if ver_type == TxType1D::IDT {
        let scale = identity_scale(coded_h);
        for row in 0..coded_h {
            for col in 0..coded_w {
                intermediate[row * coded_w + col] =
                    round_shift(temp[row * coded_w + col] as i64 * scale, shift2);
            }
        }
    } else {
        for col in 0..coded_w {
            for spatial_row in 0..coded_h {
                let mut sum = 0i64;
                for freq_row in 0..coded_h {
                    sum += kernel_value(ver_type, coded_h, freq_row, spatial_row)
                        * temp[freq_row * coded_w + col] as i64;
                }
                intermediate[spatial_row * coded_w + col] = round_shift(sum, shift2);
            }
        }
    }

    let expand_w = out_w > coded_w;
    let expand_h = out_h > coded_h;

    if !expand_w && !expand_h {
        return intermediate;
    }

    let mut output = vec![0i32; out_w * out_h];
    for row in 0..coded_h {
        for col in 0..coded_w {
            let val = intermediate[row * coded_w + col];
            if expand_w && expand_h {
                output[(2 * row) * out_w + 2 * col] = val;
                output[(2 * row) * out_w + 2 * col + 1] = val;
                output[(2 * row + 1) * out_w + 2 * col] = val;
                output[(2 * row + 1) * out_w + 2 * col + 1] = val;
            } else if expand_w {
                output[row * out_w + 2 * col] = val;
                output[row * out_w + 2 * col + 1] = val;
            } else {
                output[(2 * row) * out_w + col] = val;
                output[(2 * row + 1) * out_w + col] = val;
            }
        }
    }

    output
}

fn forward_wht_1d(src: [i32; 4]) -> [i32; 4] {
    let mut a = src[0];
    let mut b = src[1];
    let mut c = src[2];
    let mut d = src[3];

    a += b;
    d -= c;
    let e = (a - d) >> 1;
    b = e - b;
    c = e - c;
    a -= c;
    d += b;

    [a, c, d, b]
}

fn inverse_wht_1d(src: [i32; 4], shift: u32) -> [i32; 4] {
    let mut a = src[0] >> shift;
    let mut c = src[1] >> shift;
    let mut d = src[2] >> shift;
    let mut b = src[3] >> shift;

    a += c;
    d -= b;
    let e = (a - d) >> 1;
    b = e - b;
    c = e - c;
    a -= b;
    d += c;

    [a, b, c, d]
}

pub fn forward_wht4x4(residual: &[i32; 16]) -> [i32; 16] {
    let mut columns = [0i32; 16];
    for col in 0..4 {
        let src = [
            residual[col],
            residual[4 + col],
            residual[8 + col],
            residual[12 + col],
        ];
        let out = forward_wht_1d(src);
        for row in 0..4 {
            columns[row * 4 + col] = out[row];
        }
    }

    let mut coeffs = [0i32; 16];
    for row in 0..4 {
        let src = [
            columns[row * 4],
            columns[row * 4 + 1],
            columns[row * 4 + 2],
            columns[row * 4 + 3],
        ];
        let out = forward_wht_1d(src);
        coeffs[row * 4..row * 4 + 4].copy_from_slice(&out);
    }

    coeffs
}

pub fn inverse_wht4x4_lossless(levels: &[i32; 16]) -> [i32; 16] {
    let mut dequant = [0i32; 16];
    for i in 0..16 {
        dequant[i] = levels[i] * 8;
    }

    let mut rows = [0i32; 16];
    for row in 0..4 {
        let src = [
            dequant[row * 4],
            dequant[row * 4 + 1],
            dequant[row * 4 + 2],
            dequant[row * 4 + 3],
        ];
        let out = inverse_wht_1d(src, 3);
        rows[row * 4..row * 4 + 4].copy_from_slice(&out);
    }

    let mut residual = [0i32; 16];
    for col in 0..4 {
        let src = [rows[col], rows[4 + col], rows[8 + col], rows[12 + col]];
        let out = inverse_wht_1d(src, 0);
        for row in 0..4 {
            residual[row * 4 + col] = out[row];
        }
    }

    residual
}

